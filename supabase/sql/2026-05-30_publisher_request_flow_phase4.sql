  end if;

  if normalized_status is not null
    and normalized_status not in ('pending_review', 'needs_changes', 'approved', 'rejected') then
    raise exception 'publisher request status filter is invalid';
  end if;

  return query
  select
    publisher_requests.id::bigint,
    user_profiles.email::text,
    publisher_requests.full_name::text,
    publisher_requests.organizer_type::text,
    publisher_requests.commercial_name::text,
    publisher_requests.city_id::bigint,
    cities.name::text,
    publisher_requests.phone::text,
    publisher_requests.instagram::text,
    publisher_requests.website::text,
    publisher_requests.activity_description::text,
    publisher_requests.has_physical_location::boolean,
    publisher_requests.address_line_1::text,
    publisher_requests.review_status::text,
    publisher_requests.user_feedback_summary::text,
    publisher_requests.user_feedback_json::jsonb,
    publisher_requests.internal_review_notes::text,
