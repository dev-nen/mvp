create or replace function public.normalize_publisher_request_payload(p_payload jsonb)
returns table (
  full_name text,
  organizer_type text,
  commercial_name text,
  city_id bigint,
  phone text,
  instagram text,
  website text,
  activity_description text,
  has_physical_location boolean,
  address_line_1 text
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  normalized_organizer_type text;
  normalized_city_id bigint;
  normalized_has_physical_location boolean;
  raw_website text;
  normalized_website text;
begin
  if p_payload is null or jsonb_typeof(p_payload) <> 'object' then
    raise exception 'publisher request payload must be a JSON object';
  end if;

  full_name := nullif(trim(coalesce(p_payload ->> 'full_name', '')), '');
  normalized_organizer_type := lower(trim(coalesce(p_payload ->> 'organizer_type', '')));
  commercial_name := nullif(trim(coalesce(p_payload ->> 'commercial_name', '')), '');
  phone := nullif(trim(coalesce(p_payload ->> 'phone', '')), '');
  instagram := nullif(trim(coalesce(p_payload ->> 'instagram', '')), '');
  activity_description := nullif(trim(coalesce(p_payload ->> 'activity_description', '')), '');
  address_line_1 := nullif(trim(coalesce(p_payload ->> 'address_line_1', '')), '');

  normalized_has_physical_location := coalesce(
    nullif(trim(coalesce(p_payload ->> 'has_physical_location', '')), '')::boolean,
    false
  );

  if full_name is null then
    raise exception 'full_name is required';
  end if;

  if normalized_organizer_type not in ('individual', 'company_or_entity') then
    raise exception 'organizer_type is invalid';
  end if;

  organizer_type := normalized_organizer_type;

  if organizer_type = 'company_or_entity' and commercial_name is null then
    raise exception 'commercial_name is required for company_or_entity';
  end if;

  if organizer_type <> 'company_or_entity' then
    normalized_has_physical_location := false;
  end if;

  has_physical_location := normalized_has_physical_location;

  if has_physical_location and address_line_1 is null then
    raise exception 'address_line_1 is required for physical locations';
  end if;

  if not (coalesce(p_payload ->> 'city_id', '') ~ '^\d+$') then
    raise exception 'city_id is required';
  end if;

  normalized_city_id := (p_payload ->> 'city_id')::bigint;

  if not exists (
    select 1
    from public.cities
    where id = normalized_city_id
      and is_active = true
      and place_type = 'municipality'
      and country_code = 'ES'
      and municipality_code is not null
      and dir3_code is not null
  ) then
    raise exception 'city_id must reference an active ES municipality';
  end if;

  city_id := normalized_city_id;

  if phone is null then
    raise exception 'phone is required';
  end if;

  if activity_description is null then
    raise exception 'activity_description is required';
  end if;

  raw_website := nullif(trim(coalesce(p_payload ->> 'website', '')), '');

  if raw_website is null then
    normalized_website := null;
  elsif raw_website !~* '^[a-z][a-z0-9+.-]*://' then
    normalized_website := 'https://' || raw_website;
  else
    normalized_website := raw_website;
  end if;

  if normalized_website is not null and normalized_website !~* '^https?://[^[:space:]]+\.[^[:space:]]+' then
    raise exception 'website must be an http or https URL';
  end if;

  website := normalized_website;

  if instagram is not null and instagram ~ '[[:space:]]' then
    raise exception 'instagram must not contain spaces';
  end if;

  return next;
end;
$$;

create or replace function public.get_my_publisher_status()
returns table (
  status text,
  latest_request_id bigint,
  latest_request jsonb,
  active_profile jsonb,
  can_submit_activities boolean,
  can_request boolean,
  can_resubmit boolean,
  user_feedback_summary text,
  user_feedback_json jsonb
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  latest_request_row public.publisher_requests;
  active_profile_row public.publisher_profiles;
  resolved_status text := 'not_requested';
begin
  if auth.uid() is null then
    raise exception 'auth.uid() is required';
  end if;

  select *
  into latest_request_row
  from public.publisher_requests
  where user_id = auth.uid()
  order by submitted_at desc, id desc
  limit 1;

  select *
  into active_profile_row
  from public.publisher_profiles
  where user_id = auth.uid()
    and is_active = true
  order by approved_at desc, id desc
  limit 1;

  if active_profile_row.id is not null then
    resolved_status := 'approved';
  elsif latest_request_row.id is not null then
    resolved_status := latest_request_row.review_status;
  end if;

  return query
  select
    resolved_status::text,
    latest_request_row.id::bigint,
    case
      when latest_request_row.id is null then null::jsonb
      else jsonb_strip_nulls(jsonb_build_object(
        'id', latest_request_row.id,
        'status', latest_request_row.review_status,
        'organizer_type', latest_request_row.organizer_type,
        'full_name', latest_request_row.full_name,
        'commercial_name', latest_request_row.commercial_name,
        'city_id', latest_request_row.city_id,
        'phone', latest_request_row.phone,
        'instagram', latest_request_row.instagram,
        'website', latest_request_row.website,
        'activity_description', latest_request_row.activity_description,
        'has_physical_location', latest_request_row.has_physical_location,
        'address_line_1', latest_request_row.address_line_1,
        'user_feedback_summary', latest_request_row.user_feedback_summary,
        'user_feedback_json', latest_request_row.user_feedback_json,
        'reviewed_at', latest_request_row.reviewed_at,
        'submitted_at', latest_request_row.submitted_at,
        'updated_at', latest_request_row.updated_at
      ))
    end,
    case
      when active_profile_row.id is null then null::jsonb
      else jsonb_strip_nulls(jsonb_build_object(
        'id', active_profile_row.id,
        'organizer_type', active_profile_row.organizer_type,
        'full_name', active_profile_row.full_name,
        'commercial_name', active_profile_row.commercial_name,
        'city_id', active_profile_row.city_id,
        'phone', active_profile_row.phone,
        'instagram', active_profile_row.instagram,
        'website', active_profile_row.website,
        'activity_description', active_profile_row.activity_description,
        'has_physical_location', active_profile_row.has_physical_location,
        'address_line_1', active_profile_row.address_line_1,
        'approved_at', active_profile_row.approved_at
      ))
    end,
    (active_profile_row.id is not null and active_profile_row.is_active = true)::boolean,
    (resolved_status in ('not_requested', 'rejected'))::boolean,
    (latest_request_row.id is not null and resolved_status in ('needs_changes', 'rejected'))::boolean,
    latest_request_row.user_feedback_summary::text,
    coalesce(latest_request_row.user_feedback_json, '[]'::jsonb)::jsonb;
end;
$$;

create or replace function public.submit_my_publisher_request(p_payload jsonb)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  normalized_payload record;
  latest_request_row public.publisher_requests;
  new_request_id bigint;
begin
  if auth.uid() is null then
    raise exception 'auth.uid() is required';
  end if;

  if exists (
    select 1
    from public.publisher_profiles
    where user_id = auth.uid()
      and is_active = true
  ) then
    raise exception 'publisher profile is already approved';
  end if;

  select *
  into latest_request_row
  from public.publisher_requests
  where user_id = auth.uid()
  order by submitted_at desc, id desc
  limit 1;

  if latest_request_row.review_status in ('pending_review', 'needs_changes', 'approved') then
    raise exception 'publisher request cannot be submitted in current status';
  end if;

  select *
  into normalized_payload
  from public.normalize_publisher_request_payload(p_payload);

  insert into public.publisher_requests (
    user_id,
    supersedes_request_id,
    review_status,
    organizer_type,
    full_name,
    commercial_name,
    city_id,
    phone,
    instagram,
    website,
    activity_description,
    has_physical_location,
    address_line_1
  )
  values (
    auth.uid(),
    case when latest_request_row.review_status = 'rejected' then latest_request_row.id else null end,
    'pending_review',
    normalized_payload.organizer_type,
    normalized_payload.full_name,
    normalized_payload.commercial_name,
    normalized_payload.city_id,
    normalized_payload.phone,
    normalized_payload.instagram,
    normalized_payload.website,
    normalized_payload.activity_description,
    normalized_payload.has_physical_location,
    normalized_payload.address_line_1
  )
  returning id into new_request_id;

  return new_request_id;
end;
$$;

create or replace function public.resubmit_my_publisher_request(
  p_request_id bigint,
  p_payload jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  previous_request_row public.publisher_requests;
  normalized_payload record;
  new_request_id bigint;
begin
  if auth.uid() is null then
    raise exception 'auth.uid() is required';
  end if;

  select *
  into previous_request_row
  from public.publisher_requests
  where id = p_request_id
    and user_id = auth.uid()
  limit 1;

  if previous_request_row.id is null then
    raise exception 'publisher request is not available for current user';
  end if;

  if previous_request_row.review_status not in ('needs_changes', 'rejected') then
    raise exception 'publisher request is not available for resubmission';
  end if;

  if exists (
    select 1
    from public.publisher_profiles
    where user_id = auth.uid()
      and is_active = true
  ) then
    raise exception 'publisher profile is already approved';
  end if;

  if exists (
    select 1
    from public.publisher_requests
    where user_id = auth.uid()
      and review_status = 'pending_review'
  ) then
    raise exception 'publisher request is already pending review';
  end if;

  select *
  into normalized_payload
  from public.normalize_publisher_request_payload(p_payload);

  insert into public.publisher_requests (
    user_id,
    supersedes_request_id,
    review_status,
    organizer_type,
    full_name,
    commercial_name,
    city_id,
    phone,
    instagram,
    website,
    activity_description,
    has_physical_location,
    address_line_1
  )
  values (
    auth.uid(),
    previous_request_row.id,
    'pending_review',
    normalized_payload.organizer_type,
    normalized_payload.full_name,
    normalized_payload.commercial_name,
    normalized_payload.city_id,
    normalized_payload.phone,
    normalized_payload.instagram,
    normalized_payload.website,
    normalized_payload.activity_description,
    normalized_payload.has_physical_location,
    normalized_payload.address_line_1
  )
  returning id into new_request_id;

  return new_request_id;
end;
$$;

