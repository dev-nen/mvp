  left join public.user_profiles
    on user_profiles.id = publisher_requests.user_id
  left join public.cities
    on cities.id = publisher_requests.city_id
  where normalized_status is null
    or publisher_requests.review_status = normalized_status
  order by publisher_requests.submitted_at desc, publisher_requests.id desc;
